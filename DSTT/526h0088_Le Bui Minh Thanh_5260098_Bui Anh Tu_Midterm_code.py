def px_function(a):
  B = []
  for i in range(len(a)):
    if i == 0:
      B.append(f"{a[i]:.4f}")
      continue
    if i == 1 and a[i] >= 0.0:
      B.append(f"+ {a[i]:.4f}x")
      continue
    if i == 1 and a[i] < 0.0:
      B.append(f"- {abs(a[i]):.4f}x")
      continue
    if i > 1:
      if a[i] < 0.0:
        B.append(f"- {abs(a[i]):.4f}x^{i}")
      if a[i] >= 0.0:
        B.append(f"+ {a[i]:.4f}x^{i}")
  B_str = ("p(x) = " + " ".join(str(x) for x in B))
  return B_str
